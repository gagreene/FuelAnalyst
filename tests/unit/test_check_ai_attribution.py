import importlib.util
from pathlib import Path

import pytest

_SPEC = importlib.util.spec_from_file_location(
    'check_ai_attribution', Path(__file__).resolve().parents[2] / 'scripts' / 'check_ai_attribution.py')
check = importlib.util.module_from_spec(_SPEC)
_SPEC.loader.exec_module(check)

FOOTER = 'Generated with [Claude' + ' Code](https://claude.com/claude-code)'


@pytest.mark.parametrize('text', [
    'Fix a bug\n\nBody text\n\n\U0001F916 ' + FOOTER,
    FOOTER,
    'Fix\n\nCo-Authored-By: Claude <noreply@anthropic.com>',
    'Fix\n\nco-authored-by: GitHub Copilot <copilot@example.com>',
    'Generated by ChatGPT',
    'a \U0001F916 in the middle',
])
def test_attribution_is_found(text):
    assert check.find_attributions(text)


@pytest.mark.parametrize('text', [
    'Address Copilot review: reproject point coordinates',
    'Add the .claude/ folder to .gitignore',
    'Regenerated with the script from a clean clone',
    'Co-authored-by: Jane Smith <jane@example.com>',
    'Fix cursor position in the tutorial',
    '',
])
def test_ordinary_text_is_clean(text):
    assert check.find_attributions(text) == []


def test_main_reports_and_fails_on_a_file(tmp_path, capsys):
    bad = tmp_path / 'msg.txt'
    bad.write_text('Fix\n\n' + FOOTER, encoding='utf-8')

    assert check.main(['--label', 'commit abc', str(bad)]) == 1
    assert 'commit abc: generated-with line' in capsys.readouterr().err


def test_main_passes_a_clean_file(tmp_path):
    good = tmp_path / 'msg.txt'
    good.write_text('Fix a bug\n', encoding='utf-8')

    assert check.main([str(good)]) == 0
